/**
 * Hex encode/decode for 32-byte key seeds, the form a wallet stores them in.
 *
 * `fromHex` validates so a corrupt stored seed is refused instead of silently producing zero-filled,
 * and so wrong, keys, which would misattribute every signed op.
 */
export function toHex(bytes: Uint8Array): string {
  return Array.from(bytes, (b) => b.toString(16).padStart(2, "0")).join("");
}

export function fromHex(hex: string): Uint8Array {
  if (hex.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(hex)) {
    throw new Error("invalid hex");
  }
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}
