#!/usr/bin/env node
/**
 * Gate: a core package's public API changes only on purpose.
 *
 * `doc/core-compatibility.md` defines a core package's public API as every name its `exports` map
 * reaches, and makes removing or renaming one a major version. Nothing shows that in review unless
 * the names are written down, so each core package commits its list as `public-api.txt`, one
 * `<entry point> <value|type> <name>` line per export, and this checks the list against the source.
 *
 *     node scripts/check-core-api.mjs            # fail when a list drifts from the source
 *     node scripts/check-core-api.mjs --write    # rewrite the lists after a deliberate change
 *
 * It reads the TypeScript source, not `dist`, so it needs no build: an entry's `types` path
 * (`./dist/signing-conformance.d.ts`) maps back to `src/signing-conformance.ts`. A name that is
 * both a value and a type (a class) is listed as a value.
 *
 * A repo-wide script rather than a test, like `check-doc-examples.mjs`: the gate and CI run it on
 * every change, whichever packages the affected filter picks.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import ts from "typescript";

const repoRoot = resolve(import.meta.dirname, "..");
/**
 * The published API: the core tier and the shared client packages. Every
 * package under these directories is covered, so a new one needs a list before it can merge. The
 * tooling presets are published too, but they are config, not API. The operator console's plugin
 * contract has the same list and check in its own repository (beacon.admin).
 */
const PUBLISHED_TIERS = ["packages/core", "packages/client"];
const LIST_FILE = "public-api.txt";
const write = process.argv.includes("--write");

const HEADER = [
  "# The public API of this package: every name its `exports` map reaches.",
  "# A removed or renamed line is a major version, a new one a minor (doc/core-compatibility.md).",
  "# Generated by `node scripts/check-core-api.mjs --write`; the gate fails when it drifts.",
];

/** `./dist/foo.d.ts` → `<pkg>/src/foo.ts`, the file the entry point is built from. */
function sourceOf(pkgDir, typesPath) {
  const rel = typesPath.replace(/^\.\/dist\//, "src/").replace(/\.d\.ts$/, ".ts");
  return join(pkgDir, rel);
}

/** Every `<entry> <kind> <name>` line the package's exports map reaches, sorted. */
function apiLines(pkgDir) {
  const manifest = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
  // A string target is a plain file (`"./package.json": "./package.json"`, for tooling that reads
  // the manifest); it reaches no names, so it is not part of the API list.
  const entries = Object.entries(manifest.exports ?? {})
    .filter(([, target]) => typeof target !== "string")
    .map(([entry, target]) => [entry, sourceOf(pkgDir, target.types)]);
  const program = ts.createProgram(
    entries.map(([, file]) => file),
    {
      noEmit: true,
      resolveJsonModule: true,
      esModuleInterop: true,
      skipLibCheck: true,
      moduleResolution: ts.ModuleResolutionKind.Node10, // @beaconsgg/tsconfig's "Node"
    },
  );
  const ownSource = join(pkgDir, "src");
  const checker = program.getTypeChecker();
  const lines = [];
  for (const [entry, file] of entries) {
    const source = program.getSourceFile(file);
    if (!source) throw new Error(`${relative(repoRoot, file)} (entry "${entry}") does not exist`);
    const moduleSymbol = checker.getSymbolAtLocation(source);
    for (const symbol of moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : []) {
      const target =
        symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
      // A name declared in another package resolves through that package's `dist`, which CI has
      // not built at this step, so it would list differently before and after a build (and an
      // unresolved one has no declaration at all). None exists; refuse the first, whichever form
      // it takes: `export { x } from "pkg"`, or an import exported again.
      const declarations = target.declarations ?? [];
      if (
        !declarations.length ||
        declarations.some((d) => !d.getSourceFile().fileName.startsWith(ownSource))
      ) {
        throw new Error(
          `${relative(repoRoot, pkgDir)} exports "${symbol.getName()}" from outside its own source, ` +
            "which this script can only read from a build: teach it to read that package's source first",
        );
      }
      const kind = target.flags & ts.SymbolFlags.Value ? "value" : "type";
      lines.push(`${entry} ${kind} ${symbol.getName()}`);
    }
  }
  return lines.sort();
}

const packageDirs = PUBLISHED_TIERS.flatMap((tier) =>
  readdirSync(join(repoRoot, tier))
    .sort()
    .map((name) => join(repoRoot, tier, name)),
);

const failures = [];
for (const pkgDir of packageDirs) {
  const listPath = join(pkgDir, LIST_FILE);
  const want = [...HEADER, ...apiLines(pkgDir), ""].join("\n");
  const label = relative(repoRoot, listPath);
  if (write) {
    writeFileSync(listPath, want);
    console.log(`  wrote ${label}`);
    continue;
  }
  let got = "";
  try {
    got = readFileSync(listPath, "utf8");
  } catch {
    failures.push(`${label} is missing`);
    continue;
  }
  if (got === want) {
    console.log(`  ok   ${label}`);
    continue;
  }
  const have = new Set(got.split("\n"));
  const need = new Set(want.split("\n"));
  const added = [...need].filter((line) => !have.has(line));
  const removed = [...have].filter((line) => !need.has(line));
  failures.push(
    [
      `${label} differs from the source`,
      ...added.map((line) => `      + ${line}`),
      ...removed.map((line) => `      - ${line}`),
    ].join("\n"),
  );
}

for (const failure of failures) console.log(`  FAIL ${failure}`);
if (failures.length) {
  console.error(
    "\nA core package's public API changed. If that is deliberate, run " +
      "`node scripts/check-core-api.mjs --write` and commit the lists; a removed or renamed " +
      "line is a major version (doc/core-compatibility.md).",
  );
  process.exit(1);
}
